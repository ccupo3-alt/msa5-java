package org.example.e06oop;

public class Whale {
    // 필드 (Field) : 클래스에 선언된 변수
    public static String name = "고래"; // 인스턴스 변수
    public static int age = 20; // 클래스 변수

    // 생성자 메소드
    Whale() {};

    // 메소드 (Method) : 일반적인 함수
    public void swimming() {
        System.out.println("고래가 헤엄칩니다.");
    }
}
